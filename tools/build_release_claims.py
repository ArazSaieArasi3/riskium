"""Build a bounded release-claim inventory from frozen formal receipts."""
import hashlib
import json
from pathlib import Path

ROOT = Path(__file__).resolve().parents[1]
FILES = {
    "model": ROOT / "ontology/riskium-model.json",
    "contract": ROOT / "evaluation/coverage-review.json",
    "owl": ROOT / "ontology/derived/riskium.owl.ttl",
    "hermit": ROOT / "evaluation/hermit/report.json",
    "shacl": ROOT / "evaluation/shacl/coverage-status.json",
    "c14": ROOT / "evaluation/c14-boundary-review.json",
}


def digest(path):
    return hashlib.sha256(path.read_bytes()).hexdigest()


def main():
    model = json.loads(FILES["model"].read_text())
    hermit = json.loads(FILES["hermit"].read_text())
    shacl = json.loads(FILES["shacl"].read_text())
    c14 = json.loads(FILES["c14"].read_text())
    if hermit["model_version"] != model["version"] or hermit["inputs"]["owl_turtle_sha256"] != digest(FILES["owl"]):
        raise SystemExit("HermiT receipt and OWL/model differ")
    if hermit["inputs"]["contract_sha256"] != digest(FILES["contract"]):
        raise SystemExit("HermiT contract differs")
    if shacl["source_sha256"] != digest(FILES["model"]) or shacl["contract_sha256"] != digest(FILES["contract"]):
        raise SystemExit("SHACL ledger and source/contract differ")
    if c14["inputs_sha256"]["ontology/riskium-model.json"] != digest(FILES["model"]) or c14["new_shacl_executions"] != 0:
        raise SystemExit("C-14 review differs or claims new execution")
    h = hermit["coverage"]
    s = shacl["outcomes"]
    if h["baseline_obligations"] != 295 or sum(h["outcomes"].values()) != 295:
        raise SystemExit("HermiT denominator differs")
    if shacl["baseline"] != 359 or sum(s.values()) != 359:
        raise SystemExit("SHACL denominator differs")
    h_open = [r for r in hermit["obligations"] if r["outcome"] == "NOT_RUN"]
    s_open = [r for r in shacl["obligations"] if r["outcome"] in ("NOT_RUN", "PARTIAL")]
    if len(h_open) != h["outcomes"]["NOT_RUN"] or len(s_open) != s["NOT_RUN"] + s["PARTIAL"]:
        raise SystemExit("Open row inventory differs")
    hashes = "\n".join(f"| `{path.relative_to(ROOT)}` | `{digest(path)}` |" for path in FILES.values())
    rows = "\n".join(
        f"| C-{n:02d} | {next((r['id'] + ' ' + r['outcome'] for r in h_open if r['source_element'] == f'C-{n:02d}'), '—')} | "
        f"{next((r['id'] + ' ' + r['outcome'] for r in s_open if r['source_element'] == f'C-{n:02d}'), '—')} |"
        for n in range(1, 26)
        if any(r["source_element"] == f"C-{n:02d}" for r in h_open + s_open)
    )
    output = f"""# Candidate release claims — conceptual design {model['version']}

This inventory is generated by `python3 tools/build_release_claims.py` from the exact receipts below. It prepares a **development prerelease** claim profile; it is not a tag, an independently reviewed scientific conclusion or a substitute for the release-commit freeze and clean rerun. The [release gates](../docs/first-release-profile.md) remain controlling.

| Claim | Evidence and permitted wording |
| --- | --- |
| Conceptual inventory | The structured source defines {len(model['concepts'])} catalog concepts, {len(model['associations'])} associations/bridges and {len(model['constraints'])} interpretation constraints. Its 77 typed-core classes are a bounded projection; three broad phenomena remain optional boundaries. |
| Native/OWL representation | The native exchange and OWL mapping are source-bound engineering artifacts. The OWL export excludes three optional classes and seven external bridges; mapping and schema checks have declared limits. |
| HermiT module | {sum(x['status'] == 'PASS' for x in hermit['cases'])} executed cases passed, covering {h['outcomes']['PASS']}/{h['baseline_obligations']} predeclared reasoner obligations. {h['outcomes']['NOT_RUN']} engine-specific constraint rows are NOT_RUN. This is finite scoped reasoning, not a proof of ontology-wide semantic correctness. |
| SHACL modules | {s['PASS']}/{shacl['baseline']} obligations have scoped PASS, {s['PARTIAL']} is PARTIAL and {s['NOT_RUN']} are NOT_RUN. Module cases do not establish arbitrary full-profile record admission. C-08 dual-anchor unit/scale compatibility and full multi-relation integration are pending. |
| C-14 boundary | A structural review checks three catalog boundaries, three documentary representations, seven excluded bridges and {c14['prior_admission_cases_checked']} earlier admission cases. Zero new engine executions; C-14's HermiT and SHACL rows remain NOT_RUN. |
| Independent/domain acceptance | The review inventory exists; expert judgments, requirement/CQ execution, standards interpretation and real-world applicability are not established by these engineering counts. No overall semantic-correctness percentage is claimed. |

## Outstanding formal routes in the fixed denominators

| Constraint | HermiT | SHACL |
| --- | --- | --- |
{rows}

An em dash means the engine's row has a separate PASS disposition in its own report; it does not mean another engine discharged the open row. C-08's partial SHACL evidence must retain the blocked compatibility case. Application/history and independent-review questions require explicit alternative routes; adding a generic SHACL shape would not settle them.

## Publication evidence and remaining gates

The [native Wiki](https://github.com/ArazSaieArasi3/riskium/wiki) was read back at Wiki commit `55d80eb`: six curated pages and the sidebar matched their version-controlled source byte for byte on 22 October 2026. [Pages run #1](https://github.com/ArazSaieArasi3/riskium/actions/runs/39805639835) deployed the [public generated reference](https://arazsaiearasi3.github.io/riskium/site/) from source commit `6ca90cc` and its rendered page was checked. These are publication checks, not semantic validation or a frozen release. On 22 October 2026 the project owner approved [CC BY 4.0 for scientific artifacts and MIT for software](../RIGHTS.md); [authors and affiliations](../AUTHORS.md) were matched to manuscript 7.0.6 and [citation metadata](../CITATION.cff) was added without a DOI or invented article publication. A clean candidate rehearsal at `313c967` reproduced 693 HermiT cases, all five SHACL modules and 79 regressions; the detailed receipt and initial timeout observation are recorded in #15. Final source freeze, public readback, checksums and tag/release publication remain required. No stable release or independent semantic acceptance is asserted.

## Input SHA-256

| Input | SHA-256 |
| --- | --- |
{hashes}
"""
    target = ROOT / "evaluation/release-claims.md"
    target.write_text(output)
    print(json.dumps({"version": model["version"], "hermit_open": len(h_open),
                      "shacl_open_or_partial": len(s_open), "output": str(target.relative_to(ROOT))}))


if __name__ == "__main__":
    main()
